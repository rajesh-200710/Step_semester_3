package week_12_problems.assignment_problems;

class Node {
    int data;
    Node next;

    public Node(int data) {
        this.data = data;
        this.next = null;
    }
}

public class MergingTwoWaitlists {
    public static Node merge(Node first, Node second) {
        Node dummy = new Node(0);
        Node tail = dummy;

        while (first != null && second != null) {
            if (first.data <= second.data) {
                tail.next = first;
                first = first.next;
            } else {
                tail.next = second;
                second = second.next;
            }
            tail = tail.next;
        }

        if (first != null) {
            tail.next = first;
        } else {
            tail.next = second;
        }

        return dummy.next;
    }

    public static void printList(Node head) {
        Node current = head;
        while (current != null) {
            System.out.print(current.data + " -> ");
            current = current.next;
        }
        System.out.println("null");
    }

    public static void main(String[] args) {
        Node first = new Node(3);
        first.next = new Node(8);
        first.next.next = new Node(15);

        Node second = new Node(5);
        second.next = new Node(8);
        second.next.next = new Node(20);
        second.next.next.next = new Node(25);

        Node merged = merge(first, second);
        printList(merged);
    }
}